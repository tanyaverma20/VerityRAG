"""
test_eval_dashboard_extended.py — GET /eval/dashboard's extended fields
(request D, items 6/13.E): cache stats, the 10-document benchmark, and
offline groundedness — each either real measured data or an honest
"not measured" entry, never a fabricated placeholder.
"""
import os
import shutil
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from main import app

client = TestClient(app)

# main.py resolves this path relative to its OWN location
# (Path(__file__).parent.parent / "data" / ...), not via CHROMA_DIR/
# REGISTRY_DB_PATH test isolation — it always points at the real repo's
# data/ directory regardless of which test fixtures are active. Tests that
# need to control whether this file exists must move it aside themselves
# rather than assume a particular repo state.
_GROUNDEDNESS_RESULTS_PATH = Path(__file__).parent.parent / "data" / "groundedness_eval_results.json"


@pytest.fixture()
def groundedness_file_temporarily_absent():
    """Moves the real groundedness results file aside for the duration of
    one test (if it exists) and restores it afterward — used to
    deterministically test the "not yet run" dashboard behavior regardless
    of whether backend/scripts/run_groundedness_sample.py has actually been
    run against this repo checkout."""
    backup_path = _GROUNDEDNESS_RESULTS_PATH.with_suffix(".json.testbackup")
    moved = False
    if _GROUNDEDNESS_RESULTS_PATH.exists():
        shutil.move(str(_GROUNDEDNESS_RESULTS_PATH), str(backup_path))
        moved = True
    yield
    if moved:
        shutil.move(str(backup_path), str(_GROUNDEDNESS_RESULTS_PATH))


def test_dashboard_separates_runtime_and_offline_sections():
    resp = client.get("/eval/dashboard")
    assert resp.status_code == 200
    data = resp.json()
    # Runtime/online
    assert "live" in data and "cache" in data
    # Offline
    assert "offline_retrieval_eval" in data
    assert "offline_benchmark_10_document" in data
    assert "offline_groundedness_eval" in data
    assert "not_measured" in data


def test_dashboard_cache_stats_are_real_not_fabricated():
    resp = client.get("/eval/dashboard")
    data = resp.json()
    cache_stats = data["cache"]
    assert cache_stats is not None
    assert cache_stats["backend"] in ("memory", "redis")
    assert isinstance(cache_stats["answer_entries"], int)


def test_dashboard_10_document_benchmark_reflects_the_real_results_file():
    resp = client.get("/eval/dashboard")
    data = resp.json()
    bench = data["offline_benchmark_10_document"]
    # evaluation/results.json was generated by a real run earlier in this
    # session (see evaluation/README.md) and is committed to the repo, so
    # this must be populated, not null, and must reflect genuinely measured
    # values (never fabricated placeholders like exactly 0 or round numbers).
    assert bench is not None, "evaluation/results.json must exist and be read"
    assert bench["documents_benchmarked"] == 10
    assert bench["isolation_violations"] == 0
    assert bench["cross_document_contamination_found"] is False
    assert bench["production_chroma_touched"] is False
    assert isinstance(bench["retrieval_latency_mean_ms"], (int, float))


def test_dashboard_groundedness_absent_is_reported_not_measured_not_fabricated(groundedness_file_temporarily_absent):
    resp = client.get("/eval/dashboard")
    data = resp.json()
    # groundedness_eval.py is opt-in, real-LLM-call — when its results file
    # genuinely doesn't exist, the dashboard must report this honestly as
    # null with the reason explained in not_measured, never a made-up score.
    assert data["offline_groundedness_eval"] is None
    assert any("groundedness" in m.lower() for m in data["not_measured"])


def test_dashboard_groundedness_present_reflects_the_real_results_file():
    """backend/scripts/run_groundedness_sample.py was run for real against
    this repo (Phase 6 stabilization) and its output committed to
    data/groundedness_eval_results.json — when present, the dashboard must
    read and surface it exactly, not silently ignore it."""
    if not _GROUNDEDNESS_RESULTS_PATH.exists():
        pytest.skip("data/groundedness_eval_results.json not present in this checkout")

    resp = client.get("/eval/dashboard")
    data = resp.json()
    g = data["offline_groundedness_eval"]
    assert g is not None
    assert g["source"].startswith("data/groundedness_eval_results.json")
    assert isinstance(g["dataset_size"], int) and g["dataset_size"] > 0
    # The real run hit Groq's free-tier rate limit for most/all questions —
    # a genuine external constraint. The dashboard must surface whatever
    # the file actually says (even "NOT_MEASURED" as a sentinel string),
    # never silently substitute a fabricated number. This assertion is
    # deliberately permissive about the VALUE (numeric or the NOT_MEASURED
    # sentinel are both valid depending on whether the real run succeeded)
    # while still proving the field is wired through correctly.
    assert g["avg_groundedness_score"] == "NOT_MEASURED" or isinstance(g["avg_groundedness_score"], (int, float))
    # `not_measured` legitimately still lists OTHER, unconditional caveats
    # that happen to mention "groundedness" in passing (e.g. the
    # hallucination_rate-as-a-single-scalar note) — what must NOT be
    # present once the file is real is specifically the "hasn't been run
    # yet" entry that points at running groundedness_eval.py.
    assert not any("results file not found" in m.lower() or "run backend/groundedness_eval.py" in m for m in data["not_measured"]), (
        "Once a real groundedness results file exists, the 'not yet run' entry must not still appear"
    )
